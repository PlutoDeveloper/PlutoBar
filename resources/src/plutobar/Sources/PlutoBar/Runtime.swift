// PlutoBar inside VoiceOS's main process (loaded as a native module by
// src/main/local/plutobar/index.js). JS calls in on the main thread; every
// call takes or gives one JSON object.
import AppKit

final class PlutoRuntime {
  static let shared = PlutoRuntime()
  let controller = PlutoController()
  let setup = SetupController()
  let settings = SettingsController()
  private var pasteboardCount = NSPasteboard.general.changeCount
  private var pasteboardTimer: Timer?

  private init() {
    // Clipboard history: tell JS each time something new is copied. Copies a
    // password manager marks concealed or transient are never kept
    // (nspasteboard.org conventions).
    pasteboardTimer = Timer.scheduledTimer(withTimeInterval: 1.0, repeats: true) { [weak self] _ in self?.checkPasteboard() }
    // Tolerance lets macOS fold this into other wakeups (less energy).
    pasteboardTimer?.tolerance = 0.5
    // scripts/dev: `plutobar.sh show {json}` / `plutobar.sh hide`.
    DistributedNotificationCenter.default().addObserver(forName: NSNotification.Name("com.voiceos.plutobar.debug"), object: nil, queue: .main) { [weak self] note in
      let parts = (note.object as? String ?? "").split(separator: " ", maxSplits: 1).map(String.init)
      if parts.first == "show" { self?.show(parts.count > 1 ? parts[1] : "{}") }
      if parts.first == "hide" { self?.controller.hide() }
      if parts.first == "key", parts.count > 1 { self?.controller.debugKey(parts[1]) }
      if parts.first == "agent", parts.count > 1 { self?.agentEvent(parts[1]) }
      if parts.first == "setup" { self?.setup.show() }
      if parts.first == "settings" { self?.settings.show(pane: parts.count > 1 ? parts[1] : nil) }
      if parts.first == "setupStep", parts.count > 1, let n = Int(parts[1]), let s = SetupModel.Step(rawValue: n) { self?.setup.model.go(to: s) }
    }
  }

  private func checkPasteboard() {
    let pb = NSPasteboard.general
    guard pb.changeCount != pasteboardCount else { return }
    pasteboardCount = pb.changeCount
    let types = Set((pb.types ?? []).map(\.rawValue))
    let concealed = types.contains("org.nspasteboard.ConcealedType") || types.contains("org.nspasteboard.TransientType")
      || types.contains("org.nspasteboard.AutoGeneratedType") || types.contains("com.agilebits.onepassword")
    let source = NSWorkspace.shared.frontmostApplication?.localizedName ?? ""
    controller.model.act(["a": "clipboard", "concealed": concealed, "app": source])
  }

  private static func object(_ json: String) -> [String: Any] {
    guard let data = json.data(using: .utf8), let o = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else { return [:] }
    return o
  }

  // {"key": bool, "scope": "apps|files|actions|clipboard", "query": "…", "toggle": bool}
  func show(_ json: String) {
    let o = Self.object(json)
    let model = controller.model
    if o["toggle"] as? Bool == true, controller.isVisible, !model.holdsOpen {
      controller.hide()
      return
    }
    // Open first (it starts fresh), then apply what was asked for.
    controller.show(key: o["key"] as? Bool ?? true)
    if let s = o["scope"] as? String { model.setScope(PlutoModel.Scope(rawValue: s)) }
    if let q = o["query"] as? String {
      model.query = q
      model.queryChanged()
    }
  }

  // {"seq", "sections": […], "selected"} or {"update": item}
  func results(_ json: String) {
    let o = Self.object(json)
    if let item = o["update"] as? [String: Any] {
      controller.model.updateItem(item)
    } else {
      controller.model.setResults(o)
    }
  }

  func agentEvent(_ json: String) {
    let o = Self.object(json)
    if controller.model.handleAgent(o) {
      // A voice turn or an approval brings the bar up. A voice turn leaves
      // the keyboard where it is; an approval needs it.
      controller.show(key: o["t"] as? String == "confirm" || controller.isVisible)
    }
  }

  func state(_ json: String) { controller.model.setState(Self.object(json)) }
}

// MARK: - Node-API entry points (Sources/PlutoAddon/addon.c)

@_cdecl("plutobar_start")
public func plutobarStart() { _ = PlutoRuntime.shared }

@_cdecl("plutobar_show")
public func plutobarShow(_ json: UnsafePointer<CChar>) { PlutoRuntime.shared.show(String(cString: json)) }

@_cdecl("plutobar_hide")
public func plutobarHide() { PlutoRuntime.shared.controller.hide() }

@_cdecl("plutobar_is_visible")
public func plutobarIsVisible() -> Bool { PlutoRuntime.shared.controller.isVisible }

@_cdecl("plutobar_results")
public func plutobarResults(_ json: UnsafePointer<CChar>) { PlutoRuntime.shared.results(String(cString: json)) }

@_cdecl("plutobar_agent_event")
public func plutobarAgentEvent(_ json: UnsafePointer<CChar>) { PlutoRuntime.shared.agentEvent(String(cString: json)) }

@_cdecl("plutobar_state")
public func plutobarState(_ json: UnsafePointer<CChar>) { PlutoRuntime.shared.state(String(cString: json)) }

@_cdecl("plutobar_setup_show")
public func plutobarSetupShow() { PlutoRuntime.shared.setup.show() }

@_cdecl("plutobar_setup_close")
public func plutobarSetupClose() { PlutoRuntime.shared.setup.close() }

@_cdecl("plutobar_setup_visible")
public func plutobarSetupVisible() -> Bool { PlutoRuntime.shared.setup.isVisible }

@_cdecl("plutobar_setup_state")
public func plutobarSetupState(_ json: UnsafePointer<CChar>) {
  guard let data = String(cString: json).data(using: .utf8), let o = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else { return }
  PlutoRuntime.shared.setup.model.update(o)
}

// {"pane": "general|search|pluto|apps|dictation|permissions|about"}
@_cdecl("plutobar_settings_show")
public func plutobarSettingsShow(_ json: UnsafePointer<CChar>) {
  let data = String(cString: json).data(using: .utf8) ?? Data()
  let o = (try? JSONSerialization.jsonObject(with: data) as? [String: Any]) ?? [:]
  PlutoRuntime.shared.settings.show(pane: o["pane"] as? String)
}

@_cdecl("plutobar_settings_state")
public func plutobarSettingsState(_ json: UnsafePointer<CChar>) {
  guard let data = String(cString: json).data(using: .utf8), let o = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else { return }
  PlutoRuntime.shared.settings.model.update(o)
}

@_cdecl("plutobar_settings_visible")
public func plutobarSettingsVisible() -> Bool { PlutoRuntime.shared.settings.isVisible }
